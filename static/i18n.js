let currentLanguage = "en";
try { currentLanguage = localStorage.getItem("microfund-language") === "zh" ? "zh" : "en"; } catch { /* Storage may be unavailable. */ }

export function language() { return currentLanguage; }

export function t(key, values = {}) {
  const template = messages[currentLanguage][key] ?? messages.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

export function applyLanguage() {
  document.documentElement.lang = currentLanguage === "zh" ? "zh-CN" : "en";
  document.title = t("pageTitle");
  document.querySelectorAll("[data-i18n]").forEach((element) => { element.textContent = t(element.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => { element.setAttribute("aria-label", t(element.dataset.i18nAria)); });
  const toggle = document.getElementById("language-toggle");
  toggle.textContent = currentLanguage === "en" ? "中文" : "English";
  toggle.setAttribute("aria-label", currentLanguage === "en" ? t("switchToChinese") : t("switchToEnglish"));
}

export function setLanguage(value) {
  currentLanguage = value === "zh" ? "zh" : "en";
  try { localStorage.setItem("microfund-language", currentLanguage); } catch { /* Keep the in-page selection. */ }
  applyLanguage();
}
